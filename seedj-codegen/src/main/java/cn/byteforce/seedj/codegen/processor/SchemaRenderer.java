package cn.byteforce.seedj.codegen.processor;

import cn.byteforce.seedj.codegen.MaskerName;
import cn.byteforce.seedj.domain.FieldType;
import java.util.Map;

/**
 * 把 {@link ObjectModel} 渲染成三种产物：
 *
 * <ol>
 *   <li>生成的 {@code ObjectSchema} Java 源码（字段唯一来源）；
 *   <li>OpenAPI 片段（可被契约文档或网关直接消费）；
 *   <li>迁移候选 SQL（建表 + 追加列；只生成候选，人工审阅后提交）。
 * </ol>
 *
 * <p>渲染是纯函数：同样的模型永远得到同样的字节，便于构建可复现与生成物审阅。
 *
 * @author ByteForce
 * @since 1.0.0
 */
final class SchemaRenderer {

    private static final Map<FieldType, String> OPENAPI_TYPES =
            Map.of(
                    FieldType.TEXT, "type: string",
                    FieldType.INTEGER, "type: integer\n          format: int32",
                    FieldType.LONG, "type: integer\n          format: int64",
                    FieldType.DECIMAL, "type: number",
                    FieldType.BOOLEAN, "type: boolean",
                    FieldType.DATE, "type: string\n          format: date",
                    FieldType.TIMESTAMP, "type: string\n          format: date-time",
                    FieldType.UUID, "type: string\n          format: uuid");

    private SchemaRenderer() {}

    /**
     * 渲染 ObjectSchema 源码。
     *
     * @param model 对象模型
     * @return Java 源码
     */
    static String javaSource(ObjectModel model) {
        StringBuilder out = new StringBuilder(1024);
        out.append("// Generated by seedj-codegen from ")
                .append(model.recordName())
                .append("; do not edit.\n");
        out.append("package ").append(model.packageName()).append(";\n\n");
        out.append("import cn.byteforce.seedj.domain.FieldDefinition;\n");
        out.append("import cn.byteforce.seedj.domain.FieldType;\n");
        out.append("import cn.byteforce.seedj.domain.ObjectSchema;\n");
        out.append("import cn.byteforce.seedj.domain.Privacy;\n\n");
        out.append("/** Generated schema; the @SeedjObject record is the only field source. */\n");
        out.append("final class ").append(model.schemaClassName()).append(" {\n\n");
        out.append("    private static final ObjectSchema SCHEMA =\n");
        out.append("            ObjectSchema.builder(\"")
                .append(model.objectType())
                .append("\", \"")
                .append(model.table())
                .append("\")\n");
        for (FieldModel field : model.fields()) {
            out.append("                    .field(new FieldDefinition(\"")
                    .append(field.name())
                    .append("\", FieldType.")
                    .append(field.type().name())
                    .append(", ")
                    .append(field.required())
                    .append(", ")
                    .append(field.writeOnly())
                    .append(", ")
                    .append(field.eventVisible())
                    .append(", ")
                    .append(field.filterable())
                    .append(", ")
                    .append(field.sortable())
                    .append(", ")
                    .append(field.indexed())
                    .append(", Privacy.")
                    .append(field.privacy().name())
                    .append(", ")
                    .append(maskerExpression(field.masker()))
                    .append(", ")
                    .append(constraintsExpression(field.constraints()))
                    .append("))\n");
        }
        out.append("                    .build();\n\n");
        out.append("    private ").append(model.schemaClassName()).append("() {\n");
        out.append("    }\n\n");
        out.append("    static ObjectSchema schema() {\n");
        out.append("        return SCHEMA;\n");
        out.append("    }\n");
        out.append("}\n");
        return out.toString();
    }

    /**
     * 渲染默认读视图：双时间轴元字段 + 全部非 writeOnly 字段。
     *
     * <p>组件名由 schema 字段名转回 camelCase；JSON 仍用 snake_case，与手写视图一致。 只生成可推导的映射，不包含任何业务规则。
     *
     * @param model 对象模型
     * @return Java 源码
     */
    static String viewSource(ObjectModel model) {
        StringBuilder out = new StringBuilder(1024);
        out.append("// Generated by seedj-codegen from ")
                .append(model.recordName())
                .append("; do not edit.\n");
        out.append("package ").append(model.packageName()).append(";\n\n");
        out.append("import tools.jackson.databind.PropertyNamingStrategies;\n");
        out.append("import tools.jackson.databind.annotation.JsonNaming;\n\n");
        out.append("/** Generated read view; writeOnly fields are excluded. */\n");
        out.append("@JsonNaming(PropertyNamingStrategies.SnakeCaseStrategy.class)\n");
        out.append("public record ").append(model.viewClassName()).append("(\n");
        out.append("        java.util.UUID id,\n");
        out.append("        long version,\n");
        out.append("        java.time.Instant validFrom,\n");
        out.append("        java.time.Instant validTo");
        for (FieldModel field : model.fields()) {
            if (field.writeOnly()) {
                continue;
            }
            out.append(",\n        ")
                    .append(viewType(field.javaType()))
                    .append(' ')
                    .append(Names.camelCase(field.name()));
        }
        out.append(") {\n}\n");
        return out.toString();
    }

    private static String viewType(String javaType) {
        return javaType.startsWith("java.lang.")
                ? javaType.substring("java.lang.".length())
                : javaType;
    }

    /**
     * 渲染 OpenAPI 片段。
     *
     * @param model 对象模型
     * @return YAML
     */
    static String openApi(ObjectModel model) {
        StringBuilder out = new StringBuilder(512);
        out.append("openapi: 3.1.0\n");
        out.append("info:\n");
        out.append("  title: ").append(model.objectType()).append("\n");
        out.append("  version: 0.0.0-generated\n");
        out.append("paths: {}\n");
        out.append("components:\n");
        out.append("  schemas:\n");
        out.append("    ").append(model.objectType()).append(":\n");
        out.append("      type: object\n");
        out.append("      x-seedj:\n");
        out.append("        objectType: ").append(model.objectType()).append("\n");
        out.append("        table: ").append(model.table()).append("\n");
        out.append("      required:\n");
        for (FieldModel field : model.fields()) {
            if (field.required()) {
                out.append("        - ").append(field.name()).append("\n");
            }
        }
        out.append("      properties:\n");
        for (FieldModel field : model.fields()) {
            out.append("        ").append(field.name()).append(":\n");
            out.append("          ").append(OPENAPI_TYPES.get(field.type())).append("\n");
            if (field.writeOnly()) {
                out.append("          writeOnly: true\n");
            }
            if (field.privacy() != cn.byteforce.seedj.domain.Privacy.PUBLIC) {
                out.append("          x-privacy: ").append(field.privacy().name()).append("\n");
            }
            if (field.masker() != MaskerName.NONE) {
                out.append("          x-masker: ").append(field.masker().name()).append("\n");
            }
            appendConstraints(out, field.constraints());
        }
        return out.toString();
    }

    private static void appendConstraints(
            StringBuilder out, cn.byteforce.seedj.domain.FieldDefinition.Constraints c) {
        if (!c.enumValues().isEmpty()) {
            out.append("          enum:\n");
            for (String value : c.enumValues().stream().sorted().toList()) {
                out.append("            - ").append(yamlScalar(value)).append("\n");
            }
        }
        if (c.pattern() != null) {
            out.append("          pattern: ").append(yamlQuote(c.pattern())).append("\n");
        }
        if (c.minLength() != null) {
            out.append("          minLength: ").append(c.minLength()).append("\n");
        }
        if (c.maxLength() != null) {
            out.append("          maxLength: ").append(c.maxLength()).append("\n");
        }
        if (c.unique()) {
            out.append("          x-seedj-unique: true\n");
        }
        if (c.precision() != null) {
            out.append("          x-seedj-precision: ").append(c.precision()).append("\n");
        }
        if (c.scale() != null) {
            out.append("          x-seedj-scale: ").append(c.scale()).append("\n");
        }
    }

    /**
     * 渲染建表候选（与运行时 {@code TemporalDdl} 模板一致）。
     *
     * @param model 对象模型
     * @return SQL
     */
    static String createSql(ObjectModel model) {
        String name = model.table();
        StringBuilder sql = new StringBuilder(1024);
        sql.append(candidateHeader(model));
        sql.append("CREATE TABLE ").append(name).append(" (\n");
        sql.append("    id              eis_id        NOT NULL,\n");
        sql.append("    version         eis_version   NOT NULL DEFAULT 1,\n");
        sql.append("    valid_from      eis_timestamp NOT NULL,\n");
        sql.append("    valid_to        eis_timestamp,\n");
        sql.append("    recorded_at     eis_timestamp NOT NULL,\n");
        sql.append("    superseded_at   eis_timestamp,\n");
        sql.append("    created_by      eis_id        NOT NULL,\n");
        sql.append("    created_at      eis_timestamp NOT NULL,\n");
        sql.append("    updated_by      eis_id,\n");
        sql.append("    updated_at      eis_timestamp,\n");
        for (FieldModel field : model.fields()) {
            sql.append("    ").append(field.name()).append(' ').append(sqlType(field));
            sql.append(columnConstraints(field));
            sql.append(",\n");
        }
        sql.append("    CONSTRAINT pk_").append(name).append(" PRIMARY KEY (id, recorded_at),\n");
        sql.append(
                "    CONSTRAINT valid_range CHECK (valid_to IS NULL OR valid_to > valid_from),\n");
        sql.append("    CONSTRAINT recorded_range CHECK (superseded_at IS NULL")
                .append(" OR superseded_at > recorded_at)\n");
        sql.append(");\n");

        sql.append("CREATE UNIQUE INDEX uq_")
                .append(name)
                .append("_current ON ")
                .append(name)
                .append(" (id) WHERE superseded_at IS NULL;\n");
        for (FieldModel field :
                model.fields().stream()
                        .filter(field -> field.constraints().unique())
                        .sorted(java.util.Comparator.comparing(FieldModel::name))
                        .toList()) {
            sql.append("CREATE UNIQUE INDEX uq_")
                    .append(name)
                    .append('_')
                    .append(field.name())
                    .append(" ON ")
                    .append(name)
                    .append(" (")
                    .append(field.name())
                    .append(") WHERE superseded_at IS NULL;\n");
        }

        sql.append("ALTER TABLE ")
                .append(name)
                .append(" ADD CONSTRAINT ex_")
                .append(name)
                .append("_valid_overlap EXCLUDE USING gist (\n");
        sql.append("    id WITH =,\n");
        sql.append("    tstzrange(valid_from, valid_to, '[)') WITH &&,\n");
        sql.append("    tstzrange(recorded_at, superseded_at, '[)') WITH &&\n");
        sql.append(");\n");

        sql.append("CREATE INDEX idx_")
                .append(name)
                .append("_valid_time ON ")
                .append(name)
                .append(" (valid_from, valid_to);\n");
        sql.append("CREATE INDEX idx_")
                .append(name)
                .append("_recorded_time ON ")
                .append(name)
                .append(" (recorded_at, superseded_at);\n");
        sql.append("CREATE INDEX idx_")
                .append(name)
                .append("_bitemporal ON ")
                .append(name)
                .append(" (valid_from, valid_to, recorded_at, superseded_at);\n");
        for (FieldModel field :
                model.fields().stream()
                        .filter(FieldModel::indexed)
                        .sorted(java.util.Comparator.comparing(FieldModel::name))
                        .toList()) {
            sql.append("CREATE INDEX idx_")
                    .append(name)
                    .append('_')
                    .append(field.name())
                    .append(" ON ")
                    .append(name)
                    .append(" (")
                    .append(field.name())
                    .append(") WHERE superseded_at IS NULL;\n");
        }
        sql.append(asOfFunctions(name));
        return sql.toString();
    }

    /**
     * 渲染追加列候选：每个字段一条 {@code ADD COLUMN IF NOT EXISTS}。
     *
     * <p>这是给「已有表加字段」的候选：人工审阅后把需要的语句合并进 V2、V3…， 生成器不会执行迁移，也不会改已发布的 V1。
     *
     * @param model 对象模型
     * @return SQL
     */
    static String alterSql(ObjectModel model) {
        StringBuilder sql = new StringBuilder(512);
        sql.append(candidateHeader(model));
        for (FieldModel field : model.fields()) {
            sql.append("ALTER TABLE ")
                    .append(model.table())
                    .append(" ADD COLUMN IF NOT EXISTS ")
                    .append(field.name())
                    .append(' ')
                    .append(sqlType(field))
                    .append(";\n");
        }
        return sql.toString();
    }

    private static String sqlType(FieldModel field) {
        return field.type().sqlType(field.constraints().precision(), field.constraints().scale());
    }

    private static String columnConstraints(FieldModel field) {
        StringBuilder sql = new StringBuilder();
        if (field.required()) {
            sql.append(" NOT NULL");
        }
        cn.byteforce.seedj.domain.FieldDefinition.Constraints c = field.constraints();
        if (!c.enumValues().isEmpty()) {
            sql.append(" CHECK (").append(field.name()).append(" IN (");
            java.util.List<String> values = c.enumValues().stream().sorted().toList();
            for (int i = 0; i < values.size(); i++) {
                if (i > 0) {
                    sql.append(", ");
                }
                sql.append(sqlQuote(values.get(i)));
            }
            sql.append("))");
        }
        if (c.pattern() != null) {
            sql.append(" CHECK (")
                    .append(field.name())
                    .append(" ~ ")
                    .append(sqlQuote(c.pattern()))
                    .append(")");
        }
        if (c.minLength() != null) {
            sql.append(" CHECK (char_length(")
                    .append(field.name())
                    .append(") >= ")
                    .append(c.minLength())
                    .append(")");
        }
        if (c.maxLength() != null) {
            sql.append(" CHECK (char_length(")
                    .append(field.name())
                    .append(") <= ")
                    .append(c.maxLength())
                    .append(")");
        }
        return sql.toString();
    }

    private static String constraintsExpression(
            cn.byteforce.seedj.domain.FieldDefinition.Constraints c) {
        if (c.equals(cn.byteforce.seedj.domain.FieldDefinition.Constraints.NONE)) {
            return "FieldDefinition.Constraints.NONE";
        }
        StringBuilder enums = new StringBuilder("java.util.Set.of(");
        java.util.List<String> values = c.enumValues().stream().sorted().toList();
        for (int i = 0; i < values.size(); i++) {
            if (i > 0) {
                enums.append(", ");
            }
            enums.append(javaQuote(values.get(i)));
        }
        enums.append(')');
        return "new FieldDefinition.Constraints("
                + enums
                + ", "
                + javaLiteral(c.pattern())
                + ", "
                + c.minLength()
                + ", "
                + c.maxLength()
                + ", "
                + c.unique()
                + ", "
                + c.precision()
                + ", "
                + c.scale()
                + ")";
    }

    private static String javaLiteral(String value) {
        return value == null ? "null" : javaQuote(value);
    }

    private static String javaQuote(String value) {
        StringBuilder quoted = new StringBuilder(value.length() + 2).append('"');
        for (int i = 0; i < value.length(); i++) {
            char c = value.charAt(i);
            switch (c) {
                case '\\' -> quoted.append("\\\\");
                case '"' -> quoted.append("\\\"");
                case '\n' -> quoted.append("\\n");
                case '\r' -> quoted.append("\\r");
                case '\t' -> quoted.append("\\t");
                default -> quoted.append(c);
            }
        }
        return quoted.append('"').toString();
    }

    private static String yamlQuote(String value) {
        return "'" + value.replace("'", "''") + "'";
    }

    private static String yamlScalar(String value) {
        return value.matches("[A-Za-z0-9_.-]+") ? value : yamlQuote(value);
    }

    private static String sqlQuote(String value) {
        return "'" + value.replace("'", "''") + "'";
    }

    private static String candidateHeader(ObjectModel model) {
        return "-- Generated candidate by seedj-codegen from "
                + model.recordName()
                + ".\n"
                + "-- Review before committing to a versioned migration; not executed automatically.\n";
    }

    private static String maskerExpression(MaskerName masker) {
        return switch (masker) {
            case NONE -> "null";
            case LAST4 -> "cn.byteforce.seedj.domain.Maskers.last4()";
            case EMAIL -> "cn.byteforce.seedj.domain.Maskers.email()";
        };
    }

    private static String asOfFunctions(String name) {
        StringBuilder sql = new StringBuilder(512);
        sql.append("CREATE FUNCTION ")
                .append(name)
                .append("_as_of_valid")
                .append("(p_id UUID, p_time TIMESTAMPTZ) RETURNS SETOF ")
                .append(name)
                .append(" AS 'SELECT * FROM ")
                .append(name)
                .append(" WHERE id = $1 AND valid_from <= $2")
                .append(" AND (valid_to IS NULL OR valid_to > $2)'")
                .append(" LANGUAGE sql STABLE;\n");
        sql.append("CREATE FUNCTION ")
                .append(name)
                .append("_as_of_recorded")
                .append("(p_id UUID, p_time TIMESTAMPTZ) RETURNS SETOF ")
                .append(name)
                .append(" AS 'SELECT * FROM ")
                .append(name)
                .append(" WHERE id = $1 AND recorded_at <= $2")
                .append(" AND (superseded_at IS NULL OR superseded_at > $2)'")
                .append(" LANGUAGE sql STABLE;\n");
        sql.append("CREATE FUNCTION ")
                .append(name)
                .append("_as_of_bitemporal")
                .append("(p_id UUID, p_valid_time TIMESTAMPTZ, p_recorded_time TIMESTAMPTZ)")
                .append(" RETURNS SETOF ")
                .append(name)
                .append(" AS 'SELECT * FROM ")
                .append(name)
                .append(" WHERE id = $1 AND valid_from <= $2")
                .append(" AND (valid_to IS NULL OR valid_to > $2)")
                .append(" AND recorded_at <= $3")
                .append(" AND (superseded_at IS NULL OR superseded_at > $3)'")
                .append(" LANGUAGE sql STABLE;\n");
        return sql.toString();
    }
}
